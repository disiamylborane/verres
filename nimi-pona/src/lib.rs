//! # nimi-pona
//! 
//! Readable, easily and clearly pronounced identifiers based on the rules of toki pona.
//! Every two bytes are converted to a 3-syllable word.
//!
//! ## How to use
//! 
//! Use [`NimiPona<u16>`], [`NimiPona<u32>`], [`NimiPona<u64>`] and [`NimiPona<u128>`] as
//! the wrappers around primitive types that implement [`FromStr`] and [`Display`] traits
//! 
//! ```
//! use nimi_pona::NimiPona;
//! use std::str::FromStr;
//! 
//! let id = NimiPona(4242_u16);
//! assert_eq!(id.to_string(), "nupeki");
//! assert_eq!(NimiPona::from_str(&id.to_string()).unwrap(), NimiPona(4242_u16));
//! 
//! let longer_id = NimiPona(6471944860073947705_u64);
//! assert_eq!(longer_id.to_string(), "loneni sikino jasotu josimo");
//! assert_eq!(NimiPona::from_str(&longer_id.to_string()).unwrap(), NimiPona(6471944860073947705_u64));
//! ```
//! 


#![cfg_attr(not(test), no_std)]
#![warn(missing_docs)]


use core::{fmt::{Display, Debug}, str::FromStr};


/// A numeric Id that can be represented as a eadable and easily pronounceable string
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Debug)]
#[repr(transparent)]
pub struct NimiPona<T: NimiPonaConvert>(pub T);


/// An error representing an incorrect nimi-pona string for parsing
#[derive(Debug)]
#[allow(missing_docs)]
pub enum NimiPonaParseError {
    IncorrectSyllable([u8; 2]),
    IncorrectWord([[u8; 2]; 3]),
    IncorrectWordLength,
    IncorrectLength,
}


impl<T: NimiPonaConvert> Display for NimiPona<T> {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(f, "{}", self.0.display_nimipona())
    }
}



impl<T: NimiPonaConvert> FromStr for NimiPona<T> {
    type Err = NimiPonaParseError;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        Ok(Self(T::parse_nimipona(s)?))
    }
}


/// The value that may be converted to/from nimipona. Implemented for u16-u128.
pub trait NimiPonaConvert : Copy + Ord {
    /// Converts a compact id into a utf-8 string containing three-syllable words
    fn display_nimipona(self) -> impl Display;

    /// Parses the ID from the representation generated by `display_nimipona`
    fn parse_nimipona(str: &str) -> Result<Self, NimiPonaParseError>;
}


impl NimiPonaConvert for u16 {
    fn display_nimipona(self) -> impl Display {
        StringIdHolder([self])
    }
    fn parse_nimipona(str: &str) -> Result<Self, NimiPonaParseError> {
        StringIdHolder::<1>::from_str(str).map(|StringIdHolder([v])| v)
    }
}


impl NimiPonaConvert for u32 {
    fn display_nimipona(self) -> impl Display {
        let high = (self / 65536) as u16;
        let low = (self % 65536) as u16;
        StringIdHolder([low, high])
    }
    fn parse_nimipona(str: &str) -> Result<Self, NimiPonaParseError> {
        StringIdHolder::<2>::from_str(str).map(|StringIdHolder([low, high])| high as u32 * 65536 + low as u32)
    }
}


impl NimiPonaConvert for u64 {
    fn display_nimipona(self) -> impl Display {
        let mut chunks = [0u16; 4];
        for (i, chunk) in chunks.iter_mut().enumerate() {
            *chunk = (self >> (i * 16)) as u16;
        }
        StringIdHolder(chunks)
    }
    fn parse_nimipona(s: &str) -> Result<Self, NimiPonaParseError> {
        StringIdHolder::<4>::from_str(s).map(|StringIdHolder(chunks)| {
            let mut val = 0;
            for (i, &chunk) in chunks.iter().enumerate() {
                val |= (chunk as u64) << (i * 16);
            }
            val
        })
    }
}


impl NimiPonaConvert for u128 {
    fn display_nimipona(self) -> impl Display {
        let mut chunks = [0u16; 8];
        for (i, chunk) in chunks.iter_mut().enumerate() {
            *chunk = (self >> (i * 16)) as u16;
        }
        StringIdHolder(chunks)
    }

    fn parse_nimipona(s: &str) -> Result<Self, NimiPonaParseError> {
        StringIdHolder::<8>::from_str(s).map(|StringIdHolder(chunks)| {
            let mut val = 0;
            for (i, &chunk) in chunks.iter().enumerate() {
                val |= (chunk as u128) << (i * 16);
            }
            val
        })
    }
}


const WORD_SZ: u8 = 41;


struct StringIdHolder<const N: usize>([u16; N]);
impl<const N: usize> Display for StringIdHolder<N> {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        let mut space = false;
        for word in self.0 {
            if space {write!(f, " ")?}
            space = true;
            let word = word_into_nimi(word);
            let str = unsafe{str::from_utf8_unchecked(word.as_flattened())};
            write!(f, "{}", str)?
        }
        Ok(())
    }
}


impl<const N: usize> FromStr for StringIdHolder<N> {
    type Err = NimiPonaParseError;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        let mut out: [u16; N] = [0; N];
        if s.chars().filter(|&ch| ch == ' ').count() + 1 != N {
            return Err(NimiPonaParseError::IncorrectLength);
        }
        for (i, part) in s.split(' ').enumerate() {
            let (chunks, remainder) = part.as_bytes().as_chunks::<2>();
            let [] = remainder else {return Err(NimiPonaParseError::IncorrectWordLength)};
            let word: &[[u8; 2]; 3] = chunks.try_into().map_err(|_| NimiPonaParseError::IncorrectWordLength)?;
            let word = nimi_into_word(*word)?;
            out[i] = word;
        }

        Ok(Self(out))
    }
}


const fn byte_into_syllable(n: u8) -> [u8; 2] {
    match n {
        0..=29 => { // 0..30: k l m n p s × a e i o u
            const CONSONANTS: &[u8; 6] = b"klmnps";
            const VOWELS: &[u8; 5] = b"aeiou";
            [CONSONANTS[(n / 5) as usize], VOWELS[(n % 5) as usize]]
        }
        30..=37 => { // 30..38: j t × a e o u (ji and ti are forbidden)
            const CONSONANTS: &[u8; 2] = b"jt";
            const VOWELS: &[u8; 4] = b"aeou";
            let i = n - 30;
            [CONSONANTS[(i / 4) as usize], VOWELS[(i % 4) as usize]]
        }
        38..=40 => { // 38..41: w × a e i (wo and wu are forbidden)
            const VOWELS: &[u8; 3] = b"aei";
            [b'w', VOWELS[(n - 38) as usize]]
        }
        _ => unreachable!()
    }
}


const fn syllable_into_byte(s: [u8; 2]) -> Result<u8, NimiPonaParseError> {
    let consonant = s[0];
    let vowel = s[1];

    const fn with_common_vowel(cons: u8, vowel: u8) -> Option<u8> {
        let vowel_index: u8 = match vowel {
            b'a' => 0, b'e' => 1, b'i' => 2,
            b'o' => 3, b'u' => 4,
            _ => return None,
        };

        Some(cons*5+vowel_index)
    }
    const fn with_jt_vowel(cons: u8, vowel: u8) -> Option<u8> {
        let vowel_index: u8 = match vowel {
            b'a' => 0, b'e' => 1, b'o' => 2, b'u' => 3,
            _ => return None,
        };

        Some(cons+vowel_index)
    }

    match match consonant {
        b'k' => with_common_vowel(0, vowel),
        b'l' => with_common_vowel(1, vowel),
        b'm' => with_common_vowel(2, vowel),
        b'n' => with_common_vowel(3, vowel),
        b'p' => with_common_vowel(4, vowel),
        b's' => with_common_vowel(5, vowel),

        // ji and ti are forbidden
        b'j' => with_jt_vowel(30, vowel),
        b't' => with_jt_vowel(34, vowel),

        // wo and wu are forbidden
        b'w' => {
            match vowel {
                b'a' => Some(38),
                b'e' => Some(39),
                b'i' => Some(40),
                _ => None,
            }
        }

        _ => None,
    } {
        Some(v) => Ok(v),
        None => Err(NimiPonaParseError::IncorrectSyllable(s))
    }
}


const fn word_into_nimi(word: u16) -> [[u8; 2]; 3] {
    let first = (word % WORD_SZ as u16) as u8;
    let other = word / WORD_SZ as u16;
    let second = (other % WORD_SZ as u16) as u8;
    let third = (other / WORD_SZ as u16) as u8;

    [byte_into_syllable(first), byte_into_syllable(second), byte_into_syllable(third)]
}


fn nimi_into_word(word: [[u8; 2]; 3]) -> Result<u16, NimiPonaParseError> {
    let first = syllable_into_byte(word[0])? as u32;
    let second = syllable_into_byte(word[1])? as u32;
    let third = syllable_into_byte(word[2])? as u32;

    u16::try_from(first + second * WORD_SZ as u32 + third * (WORD_SZ as u32 * WORD_SZ as u32)).map_err(|_| NimiPonaParseError::IncorrectWord(word))
}


#[test]
fn test_syllable() {
    for i in 0..WORD_SZ {
        let r = syllable_into_byte(byte_into_syllable(i)).unwrap();
        assert_eq!(i, r);
    }
}


#[test]
fn test_word() {
    for i in 0..=65535 {
        let r = nimi_into_word(word_into_nimi(i)).unwrap();
        assert_eq!(i, r);
    }
}


#[test]
fn test_id() {
    let base_array = [1609u16, 18389, 65531];

    let u32_array = base_array.iter().flat_map(|&i| base_array.iter().map(move |&j| i as u32 * j as u32)).collect::<Box<[u32]>>();
    let u64_array = u32_array.iter().flat_map(|&i| u32_array.iter().map(move |&j| i as u64 * j as u64)).collect::<Box<[u64]>>();
    let u128_array = u64_array.iter().flat_map(|&i| u64_array.iter().map(move |&j| i as u128 * j as u128)).collect::<Box<[u128]>>();

    for u in base_array {
        let str = u.display_nimipona().to_string();
        let reu = u16::parse_nimipona(&str).unwrap();
        assert_eq!(u, reu);
    }
    for u in u32_array {
        let str = u.display_nimipona().to_string();
        let reu = u32::parse_nimipona(&str).unwrap();
        assert_eq!(u, reu);
    }
    for u in u64_array {
        let str = u.display_nimipona().to_string();
        let reu = u64::parse_nimipona(&str).unwrap();
        assert_eq!(u, reu);
    }
    for u in u128_array {
        let str = u.display_nimipona().to_string();
        let reu = u128::parse_nimipona(&str).unwrap();
        assert_eq!(u, reu);
    }
}
